"""check-adfgvx-j1: deterministic reproduction of the 23 J1 detections.
Run from the repo root:  ~/dev/projects/ciphers/.venv/bin/python -I verify/adfgvx/J1-repro.py
Writes verify/adfgvx/J1-REPRO.md.  No scoring, no nulls, no key search.
Reads only results/adfgvx-J0.json, results/adfgvx-J1-targets.jsonl, ciphertexts/*.json.
Never reads search/.  comp's plaintext is touched only AFTER mine is computed.
"""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from adfgvx import decrypt

def apply_edits(s, spec):
    """Edits refer to ORIGINAL positions.  ins before position p; del at p / p..p+4."""
    ins, dele = {}, set()
    for e in filter(None, spec.split(",")):
        m = re.fullmatch(r"(del|ins)(1|5)@(\d+)", e)
        assert m, e
        op, k, p = m.group(1), int(m.group(2)), int(m.group(3))
        if op == "ins":
            ins[p] = ins.get(p, 0) + k
        else:
            assert p + k <= len(s)
            dele.update(range(p, p + k))
    out = []
    for i in range(len(s) + 1):
        out.append("-" * ins.get(i, 0))          # insertion lands before original i
        if i < len(s) and i not in dele:
            out.append(s[i])
    assert max(ins, default=0) <= len(s)
    return "".join(out)

WORDS = ["DER","DIE","DAS","UND","NACH","BITTE","MIT","VON","ZU","WIR","EIN","STUNDE","UHR","ABT","ARMEE","FUNK","XX","LICH","UNG","EN","ER"]
def hits(txt):
    """Crude, UNSCORED readability proxy: occurrences of long fixed German fragments (len>=3) per 100 letters."""
    n = sum(txt.count(w) for w in WORDS if len(w) >= 3)
    return 100.0 * n / max(1, len(txt))

def agree(a, b):
    """Fraction of positions where a and b agree (same-index), over the shorter."""
    m = min(len(a), len(b))
    return sum(x == y for x, y in zip(a, b)) / max(1, m)

def dec(c, key):
    return decrypt(c, key["transposition"], key["square"]).replace("?", "-")

keys = {k["id"]: k for k in json.load(open("ciphertexts/adfgvx-1918-log.keys.json"))}
rows = {r["unit"]: r for r in json.load(open("results/adfgvx-J0.json"))["rows"]}
recs = {r["id"]: r for r in json.load(open("ciphertexts/adfgvx-1918-log.records.json"))}
tg = [json.loads(l) for l in open("results/adfgvx-J1-targets.jsonl")]
tg = [t for t in tg if not t.get("meta") and t["above"]]
assert len(tg) == 23

mine = []   # computed first
for t in tg:
    u, row = t["unit"], rows[t["unit"]]
    s = row["text"]
    pk = {}
    for kid, v in t["per_key"].items():
        pk[kid] = dict(edits=v["edits"], edited=dec(apply_edits(s, v["edits"]), keys[kid]),
                       n_edited=len(apply_edits(s, v["edits"])))
    k0 = t["argmax"]
    zero = dec(s, keys[k0])
    cr = "".join(recs[i]["printed"] for i in row["ids"])
    mine.append(dict(unit=u, argmax=k0, pk=pk, zero=zero, n=len(s), cr=dec(cr, keys[k0]), ncr=len(cr)))

L = ["# J1-REPRO: independent reproduction of the 23 J1 detections", "",
     "Generated by `verify/adfgvx/J1-repro.py` (one command, run from repo root: "
     "`~/dev/projects/ciphers/.venv/bin/python -I verify/adfgvx/J1-repro.py`). "
     "Own code (`adfgvx.py`), no `search/` access. Lost symbol `-`; a pair containing one decrypts to `-`.", "",
     "Edit semantics as briefed (positions in the ORIGINAL string; `ins` inserts unknowns before p; `del5@p` removes p..p+4). "
     "No record had an insert and a delete touching the same original position, so ordering at a tie never arose. "
     "For multi-key records each key's own edit list (`per_key`) is used; comp's `plain` is for `argmax`.", "",
     "| unit | key | edits | edited len (sym) | == comp plain | 0-edit == comp | 0-edit agreement with edited (same-index) | fixed-fragment hits/100 letters, 0-edit vs edited | creilly len / scan len | creilly decrypt (first 40) |",
     "|---|---|---|---|---|---|---|---|---|---|"]
nrep = 0
detail = []
for t, m in zip(tg, mine):
    comp = t["plain"]
    mm = m["pk"][m["argmax"]]
    eq = mm["edited"] == comp
    nrep += eq
    z = m["zero"]
    eq0 = z == comp
    # "decrypts at 0 edits": see note - report the same-key unedited text equals comp's (i.e. edits irrelevant) AND a crude flag
    L.append(f"| {m['unit']} | {m['argmax']} | {mm['edits']} | {mm['n_edited']} | **{'YES' if eq else 'NO'}** | {'yes' if eq0 else 'no'} | {agree(z, mm['edited']):.2f} | {hits(z):.1f} vs {hits(mm['edited']):.1f} |  {m['ncr']} / {m['n']} | `{m['cr'][:40]}` |")
    detail.append((t, m, eq))
L += ["", "'Decrypts at 0 edits' is NOT scored here (no scoring by brief). The hits column is a fixed-fragment count, not a statistic and not a null-calibrated test; read the full texts below. By eye, the unedited scan text is readable German across the whole length for roughly: p071A1(mostly), p071A2, p072A, p0924#1, p110D, p139A2, p142A2+p142A, p153B4+p153B, p189B3, p213D, p190G, p125B,. Treat that as a lead only; comp's 15 is theirs to define.", ""]
L += ["", "Note: p0924#1 is a split of record p0924, so creilly length 548 vs 290 is the whole record vs one half, not a transcription difference. Odd edited lengths (p062A 221, p218A 392 etc.) drop the final lone symbol in decryption; comp agrees. Where creilly length equals scan length and the 0-edit decryptions are identical (p062A, p071A2, p142A2, p194A.2, p218C, p220B) the two transcriptions agree on the whole unit modulo a few symbols.", ""]
L += ["", f"**Reproduced character for character: {nrep}/23.**", ""]
L += ["## Per detection", ""]
for t, m, eq in detail:
    L += [f"### {m['unit']} (key {m['argmax']}; keys searched: {', '.join(t['keys'])})", "",
          f"- edits {m['pk'][m['argmax']]['edits']}; edited length {m['pk'][m['argmax']]['n_edited']} symbols -> {len(m['pk'][m['argmax']]['edited'])} letters; comp plain {len(t['plain'])} letters; equal: **{eq}**",
          f"- mine : `{m['pk'][m['argmax']]['edited']}`",
          f"- comp : `{t['plain']}`",
          f"- 0 edits (scan text, {m['n']} symbols): `{m['zero']}`",
          f"- creilly printed ({m['ncr']} symbols vs scan {m['n']}; diff {m['ncr']-m['n']:+d}), 0 edits: `{m['cr']}`"]
    for kid, v in m["pk"].items():
        if kid != m["argmax"]:
            L.append(f"- other key {kid}, its edits {v['edits']}: `{v['edited']}`")
    L.append("")
open("verify/adfgvx/J1-REPRO.md", "w").write("\n".join(L))
print("reproduced", nrep, "/ 23")
for t, m, eq in detail:
    if not eq: print("MISMATCH", m["unit"])
